use crate::{
    MIN_JS_CORE,
    compiler::{
        codegen::{
            types::{HTMLGenerator, minify},
            util,
        },
        obfuscation::ObfuscatedExpr,
    },
    core::types::Attrs,
};
use indoc::indoc;
use std::fmt::Write;

impl HTMLGenerator for minify::None {
    fn write_doctype<'a>(out: &mut String, doctype: &'a str) {
        let _ = write!(out, "<!DOCTYPE {}>", doctype).unwrap();
    }

    fn write_open_tag(
        out: &mut String,
        tag: &str,
        physical_attrs: &super::types::PhysicalAttrs,
        is_void: bool,
    ) {
        if physical_attrs.has_attrs() {
            let _ = write!(
                out,
                "<{} {}{}>",
                tag,
                physical_attrs,
                if is_void { " /" } else { "" }
            );
        } else {
            let _ = write!(out, "<{}{}>", tag, if is_void { " /" } else { "" });
        }
    }

    fn write_close_tag(out: &mut String, tag: &str) {
        let _ = write!(out, r"</{}>", tag);
    }

    fn inject_js(output: &mut super::types::CompilerOutput) {
        let compiled_js = output.build_js();
        let _ = write!(
            output.html,
            indoc! {r"

                    <!-- Injected core.min.js for basic reactive utility -->
                    <script>
                        {}
                    </script>

                    <!-- Autogenerated compiled JS utility for reactivity -->
                    <script type='module'>
                    {}
                    </script>
            "},
            MIN_JS_CORE, compiled_js
        );
    }

    fn write_raw_text(out: &mut String, text: &str) {
        let _ = write!(out, "{}", text);
    }

    // TODO: Fix identation problem
    fn write_plain_css(out: &mut String, css: &str) {
        let _ = write!(out, "<style>\n\t{}\n</style>", css);
    }

    // TODO: Fix identation problem
    fn write_scoped_css(out: &mut String, css: &str, scope_id: &str) {
        let _ = write!(
            out,
            "<style>\n\t{}\n</style>",
            util::scope_css(css, scope_id)
        );
    }

    fn write_user_js_imports(out: &mut String, js: &str) {
        if !js.trim().is_empty() {
            let formatted_imports = util::normalize_indentation(js, "\t");
            if !out.is_empty() {
                out.push('\n');
            }
            out.push_str(&formatted_imports);
        }
    }

    fn write_user_js(out: &mut String, js: &str) {
        if !js.trim().is_empty() {
            let formatted_rest = util::normalize_indentation(js, "\t");
            if !out.is_empty() {
                out.push('\n');
            }
            out.push_str(&formatted_rest);
        }
    }

    fn write_comment(out: &mut String, comment: &str) {
        let _ = write!(out, "<!-- {} -->", comment);
    }

    fn write_marker(out: &mut String, marker: &ObfuscatedExpr) {
        let _ = write!(out, "{}", marker.generate_marker());
    }

    fn write_marker_pairs(out: &mut String, marker: &ObfuscatedExpr) {
        let (left, right) = marker.generate_marker_pairs();
        let _ = write!(out, "{}{}", left, right);
    }
}

