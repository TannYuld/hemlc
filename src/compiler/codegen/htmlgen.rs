impl HTMLGenerator for minify::None {
    fn write_doctype<'a>(out: &mut String, doctype: &'a str) {
        let _ = write!(out, "<!DOCTYPE {}>", doctype).unwrap();
    }

    fn write_open_tag(
        out: &mut String,
        tag: &str,
        physical_attrs: &super::types::PhysicalAttrs,
        is_void: bool,
    ) {
        if physical_attrs.has_attrs() {
            let _ = write!(
                out,
                "<{} {}{}>",
                tag,
                physical_attrs,
                if is_void { " /" } else { "" }
            );
        } else {
            let _ = write!(out, "<{}{}>", tag, if is_void { " /" } else { "" });
        }
    }

    fn write_close_tag(out: &mut String, tag: &str) {
        let _ = write!(out, r"</{}>", tag);
    }

    fn inject_js(output: &mut super::types::CompilerOutput) {
        let compiled_js = output.build_js();
        let _ = write!(
            output.html,
            indoc! {r"

                    <!-- Injected core.min.js for basic reactive utility -->
                    <script>
                        {}
                    </script>

                    <!-- Autogenerated compiled JS utility for reactivity -->
                    <script>
                    {}
                    </script>
            "},
            MIN_JS_CORE, compiled_js
        );
    }

    fn write_raw_text(out: &mut String, text: &str) {
        let _ = write!(out, "{}", text);
    }
}

impl HTMLGenerator for minify::Js {
    fn write_doctype<'a>(out: &mut String, doctype: &'a str) {
        minify::None::write_doctype(out, doctype);
    }

    fn write_open_tag(
        out: &mut String,
        tag: &str,
        physical_attrs: &super::types::PhysicalAttrs,
        is_void: bool,
    ) {
        minify::None::write_open_tag(out, tag, physical_attrs, is_void);
    }

    fn write_close_tag(out: &mut String, tag: &str) {
        minify::None::write_close_tag(out, tag);
    }

    fn inject_js(output: &mut super::types::CompilerOutput) {
        minify::All::inject_js(output);
    }

    fn write_raw_text(out: &mut String, text: &str) {
        minify::None::write_raw_text(out, text);
    }
}

impl HTMLGenerator for minify::All {
    fn write_doctype<'a>(out: &mut String, doctype: &'a str) {
        minify::None::write_doctype(out, doctype);
    }

    fn write_open_tag(
        out: &mut String,
        tag: &str,
        physical_attrs: &super::types::PhysicalAttrs,
        is_void: bool,
    ) {
        if physical_attrs.has_attrs() {
            let _ = write!(
                out,
                "<{} {}{}>",
                tag,
                physical_attrs,
                if is_void { "/" } else { "" }
            );
        } else {
            let _ = write!(out, "<{}{}>", tag, if is_void { "/" } else { "" });
        }
    }

    fn write_close_tag(out: &mut String, tag: &str) {
        minify::None::write_close_tag(out, tag);
    }

    fn inject_js(output: &mut super::types::CompilerOutput) {
        let compiled_js = output.minified_js_build();
        let _ = write!(
            output.html,
            indoc! {
            r#"<script>{}</script><script>{}</script>"#
            },
            MIN_JS_CORE, compiled_js
        );
    }

    fn write_raw_text(out: &mut String, text: &str) {
        let _ = write!(out, "{}", util::minify_text(text));
    }
}

